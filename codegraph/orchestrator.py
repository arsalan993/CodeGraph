class Orchestrator:
    def __init__(self, db: Database, workspace_root: Path):
        self.db = db
        self.workspace_root = workspace_root
        self._threads: dict[str, threading.Thread] = {}
        self._cancelled: set[str] = set()

    def create_project(self, prompt: str) -> dict:
        specification = plan(prompt)
        project_id = uid("prj")
        workspace = self.workspace_root / project_id
        Workspace(workspace)
        timestamp = now()
        self.db.execute(
            "INSERT INTO projects VALUES(?,?,?,?,?,?,?)",
            (project_id, specification["name"], prompt, "planned", str(workspace), timestamp, timestamp),
        )
        module_ids: dict[str, str] = {}
        for module in specification["modules"]:
            module_id = uid("mod")
            module_ids[module["key"]] = module_id
            self.db.execute(
                "INSERT INTO modules VALUES(?,?,?,?,?,?,?,?)",
                (module_id, project_id, module["name"], module["kind"], module["description"], "planned", module["x"], module["y"]),
            )
        self.db.many("INSERT INTO dependencies VALUES(?,?)", [
            (module_ids[source], module_ids[target]) for source, target in specification["dependencies"]
        ])
        main_agent = uid("agt")
        self.db.execute(
            "INSERT INTO agents VALUES(?,?,?,?,?,?,?,?,?,?)",
            (main_agent, project_id, None, None, "Project lead", "main", "idle", "Coordinate project execution", timestamp, timestamp),
        )
        self.db.execute(
            "INSERT INTO memories(project_id,category,author,content,version,created_at) VALUES(?,?,?,?,?,?)",
            (project_id, "requirements", "user", json.dumps({"prompt": prompt, "acceptance": specification["acceptance"]}), 1, timestamp),
        )
        self.db.event(project_id, "project.created", "Project plan and module graph created")
        return self.project(project_id)

    def list_projects(self) -> list[dict]:
        return self.db.all("SELECT * FROM projects ORDER BY created_at DESC")

    def project(self, project_id: str) -> dict:
        project = self.db.one("SELECT * FROM projects WHERE id=?", (project_id,))
        if not project:
            raise KeyError("Project not found")
        modules = self.db.all("SELECT * FROM modules WHERE project_id=? ORDER BY x,y", (project_id,))
        module_ids = [module["id"] for module in modules]
        dependencies = []
        if module_ids:
            placeholders = ",".join("?" for _ in module_ids)
            dependencies = self.db.all(
                f"SELECT source_id,target_id FROM dependencies WHERE source_id IN ({placeholders})", tuple(module_ids)
            )
        agents = self.db.all("SELECT * FROM agents WHERE project_id=? ORDER BY created_at", (project_id,))
        files = self.db.all("SELECT * FROM files WHERE project_id=? ORDER BY path", (project_id,))
        memories = self.db.all("SELECT * FROM memories WHERE project_id=? ORDER BY id DESC LIMIT 30", (project_id,))
        events = self.db.all("SELECT * FROM events WHERE project_id=? ORDER BY id DESC LIMIT 100", (project_id,))
        runs = self.db.all("SELECT * FROM runs WHERE project_id=? ORDER BY started_at DESC", (project_id,))
        for event in events:
            event["metadata"] = json.loads(event["metadata"])
        return {**project, "modules": modules, "dependencies": dependencies, "agents": agents,
                "files": files, "memories": memories, "events": events, "runs": runs}

    def start(self, project_id: str) -> dict:
        project = self.project(project_id)
        active = next((run for run in project["runs"] if run["status"] in {"queued", "running"}), None)
        if active:
            return active
        run_id = uid("run")
        self.db.execute("INSERT INTO runs VALUES(?,?,?,?,?)", (run_id, project_id, "queued", now(), None))
        thread = threading.Thread(target=self._execute, args=(project_id, run_id), daemon=True)
        self._threads[run_id] = thread
        thread.start()
        return self.db.one("SELECT * FROM runs WHERE id=?", (run_id,)) or {}

    def cancel(self, project_id: str, run_id: str) -> None:
        run = self.db.one("SELECT * FROM runs WHERE id=? AND project_id=?", (run_id, project_id))
        if not run:
            raise KeyError("Run not found")
        self._cancelled.add(run_id)
        self.db.event(project_id, "run.cancel_requested", "Cancellation requested", run_id=run_id)

    def _stop_if_cancelled(self, project_id: str, run_id: str) -> bool:
        if run_id not in self._cancelled:
            return False
        self.db.execute("UPDATE runs SET status='cancelled',finished_at=? WHERE id=?", (now(), run_id))
        self.db.execute("UPDATE projects SET status='cancelled',updated_at=? WHERE id=?", (now(), project_id))
        self.db.execute("UPDATE agents SET status='cancelled',updated_at=? WHERE project_id=? AND status='running'", (now(), project_id))
        self.db.event(project_id, "run.cancelled", "Run cancelled", run_id=run_id)
        return True

    def _agent(self, project_id: str, name: str, role: str, task: str, *, module_id: str | None,
               parent_id: str | None, status: str = "queued") -> str:
        agent_id = uid("agt")
        timestamp = now()
        self.db.execute("INSERT INTO agents VALUES(?,?,?,?,?,?,?,?,?,?)",
                        (agent_id, project_id, module_id, parent_id, name, role, status, task, timestamp, timestamp))
        self.db.event(project_id, "agent.created", f"{name} created", agent_id=agent_id, metadata={"role": role})
        return agent_id

    def _status(self, project_id: str, run_id: str, agent_id: str, status: str, message: str) -> None:
        self.db.execute("UPDATE agents SET status=?,updated_at=? WHERE id=?", (status, now(), agent_id))
        self.db.event(project_id, f"agent.{status}", message, run_id=run_id, agent_id=agent_id)

    def _execute(self, project_id: str, run_id: str) -> None:
        try:
            self.db.execute("UPDATE runs SET status='running' WHERE id=?", (run_id,))
            self.db.execute("UPDATE projects SET status='running',updated_at=? WHERE id=?", (now(), project_id))
            lead = self.db.one("SELECT * FROM agents WHERE project_id=? AND role='main' ORDER BY created_at LIMIT 1", (project_id,))
            if not lead:
                raise RuntimeError("Main agent missing")
            lead_id = lead["id"]
            self._status(project_id, run_id, lead_id, "running", "Project lead started orchestration")
            try:
                result = get_provider().complete("You coordinate a small software project.", self.project(project_id)["prompt"])
                self.db.event(project_id, "model.completed", f"Planning response received from {result.model}", run_id=run_id,
                              agent_id=lead_id, metadata={"input_tokens": result.input_tokens, "output_tokens": result.output_tokens})
            except ProviderError as exc:
                self.db.event(project_id, "model.fallback", str(exc), run_id=run_id, agent_id=lead_id)
            modules = self.db.all("SELECT * FROM modules WHERE project_id=? ORDER BY x", (project_id,))
            workspace = Workspace(Path(self.project(project_id)["workspace"]))
            keys = ["source", "storage", "kpi", "api", "dashboard"]
            for module, key in zip(modules, keys):
                if self._stop_if_cancelled(project_id, run_id): return
                coordinator = self._agent(project_id, f"{module['name']} coordinator", "module", module["description"],
                                          module_id=module["id"], parent_id=lead_id)
                coder = self._agent(project_id, f"{module['name']} coder", "coding", f"Implement {module['name']}",
                                    module_id=module["id"], parent_id=coordinator)
                self._status(project_id, run_id, coordinator, "running", f"Coordinating {module['name']}")
                self._status(project_id, run_id, coder, "running", f"Implementing {module['name']}")
                for relative, content in GENERATED_FILES[key].items():
                    workspace.write(relative, content)
                    self.db.event(project_id, "file.changed", f"Created {relative}", run_id=run_id, agent_id=coder,
                                  metadata={"module_id": module["id"], "path": relative})
                self._sync_files(project_id, module["id"], coder, workspace)
                self._status(project_id, run_id, coder, "completed", f"Implementation complete for {module['name']}")
                tester = self._agent(project_id, f"{module['name']} tester", "testing", f"Validate {module['name']}",
                                     module_id=module["id"], parent_id=coordinator)
                self._status(project_id, run_id, tester, "running", f"Validation gate checking {module['name']}")
                passed, output = workspace.validate()
                self.db.event(project_id, "validation.passed" if passed else "validation.failed",
                              f"Validation {'passed' if passed else 'failed'} for {module['name']}", run_id=run_id,
                              agent_id=tester, metadata={"output": output})
                self._status(project_id, run_id, tester, "completed" if passed else "failed", output.splitlines()[-1])
                self._status(project_id, run_id, coordinator, "completed" if passed else "failed",
                             f"{module['name']} accepted" if passed else f"{module['name']} blocked")
                self.db.execute("UPDATE modules SET status=? WHERE id=?", ("completed" if passed else "blocked", module["id"]))
                if not passed:
                    raise RuntimeError(f"Validation failed in {module['name']}")
                time.sleep(0.35)
            self.db.execute("INSERT INTO memories(project_id,category,author,content,version,created_at) VALUES(?,?,?,?,?,?)",
                            (project_id, "decision", "Project lead", "All planned modules passed the validation gate.", 1, now()))
            self._status(project_id, run_id, lead_id, "completed", "Project completed successfully")
            self.db.execute("UPDATE runs SET status='completed',finished_at=? WHERE id=?", (now(), run_id))
            self.db.execute("UPDATE projects SET status='completed',updated_at=? WHERE id=?", (now(), project_id))
            self.db.event(project_id, "run.completed", "All modules implemented and validated", run_id=run_id)
        except Exception as exc:
            self.db.execute("UPDATE runs SET status='failed',finished_at=? WHERE id=?", (now(), run_id))
            self.db.execute("UPDATE projects SET status='failed',updated_at=? WHERE id=?", (now(), project_id))
            self.db.event(project_id, "run.failed", str(exc), run_id=run_id)

    def _sync_files(self, project_id: str, module_id: str, owner: str, workspace: Workspace) -> None:
        for item in workspace.inventory():
            existing = self.db.one("SELECT id,module_id FROM files WHERE project_id=? AND path=?", (project_id, item["path"]))
            if existing:
                self.db.execute("UPDATE files SET sha256=?,size=?,updated_at=? WHERE id=?",
                                (item["sha256"], item["size"], now(), existing["id"]))
            else:
                self.db.execute("INSERT INTO files(project_id,module_id,path,owner_agent_id,sha256,size,updated_at) VALUES(?,?,?,?,?,?,?)",
                                (project_id, module_id, item["path"], owner, item["sha256"], item["size"], now()))

